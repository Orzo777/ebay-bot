"""Збирає текстовий звіт по дослідженню RAM з CSV/JSON (research/ram_study.py) + висновки. Запуск:
python research/ram_report_md.py <datadir> <outdir>"""
import csv
import json
import statistics
import sys
from collections import Counter, defaultdict

sys.path.insert(0, ".")
from ram_parse import parse_title

datadir, outdir = sys.argv[1], sys.argv[2]
cells = list(csv.DictReader(open(f"{outdir}/ram_cells.csv", encoding="utf-8-sig")))
brands = list(csv.DictReader(open(f"{outdir}/ram_brands.csv", encoding="utf-8-sig")))
rows = json.load(open(f"{datadir}/ram_rows.json", encoding="utf-8"))
cross2 = json.load(open(f"{datadir}/ram_cross2.json", encoding="utf-8"))


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


parsed = []
for r in rows.values():
    p, why = parse_title(r["title"])
    if p:
        parsed.append((r, p))
size = Counter()
for r, p in parsed:
    size[(p["gen"], p["form"], "нове" if r["cond"] in ("1000", "1500", "1750") else "вжив.")] += 1

L = []
A = L.append
A("# Дослідження ринку оперативної пам'яті (eBay.de) — 21.09.2026\n")
A("Дані: **ціни оголошень** (фіксована ціна, товар у DE), не проданих. Зібрано 20 349 лотів, розпізнано 15 449 (76%);")
A("решта — повні ПК/ноутбуки, лоти, варіації, аксесуари (відкинуто свідомо). Повні таблиці: `ram_cells.csv`, `ram_brands.csv`.")
A("Швидкість продажів — з лічильника `estimatedSoldQuantity` дилерських лотів (вибірка ≤8 лотів на клітинку); це орієнтир, не точна цифра.\n")

A("## 1. Покриття і чого немає\n")
A("- **Є:** eBay.de (усе), лоти з розташуванням AT/FR/IT/ES/NL/PL/BE/IE, eBay GB/US (з ПДВ 19% і курсом).")
A("- **Немає (свідомо):** Kleinanzeigen (скрапінг заборонений robots.txt/умовами), Amazon (немає API), Geizhals/idealo (закриті Cloudflare/умовами).")
A("  Для Kleinanzeigen потрібна ручна вибірка: 30 хвилин у Suchaufträge, див. розділ 10.")
A("- **Виробники:** розпізнано 50+ брендів модулів і чипів (Corsair, G.Skill, Kingston, Crucial, TeamGroup, Patriot, ADATA/XPG, Lexar, PNY,")
A("  Samsung, SK Hynix, Micron, Nanya та ін.); 12% лотів без бренду в назві. Нерозпізнаних брендів понад 8 лотів майже немає (Integral, ATP).\n")

A("## 2. Розмір ринку (унікальних розпізнаних лотів у зібраній вибірці)\n")
A("| Покоління / форм-фактор | Нове | Вживане |")
A("|---|--:|--:|")
for gen in ("ddr5", "ddr4", "ddr3"):
    for form in ("udimm", "sodimm", "server"):
        A(f"| {gen.upper()} {form} | {size[(gen, form, 'нове')]} | {size[(gen, form, 'вжив.')]} |")
A("\nDDR5 вживаних лотів мало (десятки): вживаний ринок DDR5 тонкий, і ціни на вживане майже дорівнюють новому (дефіцит).\n")

A("## 3. Медіани цін і швидкість по типах (клітинки із ≥5 продавців)\n")
A("«Швидка» = медіана 5 найдешевших продавців (ціна швидкого продажу); ціни з доставкою; одна ціна на продавця.\n")
A("| Тип | НОВЕ прод. | швидка | медіана | €/ГБ | ВЖИВ. прод. | швидка | медіана | €/ГБ | шт/тиж (∑ вибірки) |")
A("|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|")
for r in sorted(cells, key=lambda r: (r["gen"], r["form"], int(r["total_gb"]), r["kit"])):
    ns, us = f(r["new_sellers"]) or 0, f(r["used_sellers"]) or 0
    if ns < 5 and us < 5:
        continue
    k = f"{r['gen'].upper()} {r['form']} {r['total_gb']} ГБ {'кіт' if r['kit'] == 'kit' else '1×'}"
    A(f"| {k} | {int(ns)} | {r['new_fast']} | {r['new_med']} | {r['new_eur_gb']} | {int(us)} | {r['used_fast']} | {r['used_med']} | {r['used_eur_gb']} | {r['vel_sum_units_per_week'] or '—'} |")
A("")

A("## 4. Бренди: медіана €/ГБ (нове | вживане), лише де ≥3 лоти\n")
for gen, form in (("ddr5", "udimm"), ("ddr5", "sodimm"), ("ddr4", "udimm"), ("ddr4", "sodimm")):
    rr = [b for b in brands if b["gen"] == gen and b["form"] == form][:10]
    A(f"- **{gen.upper()} {form}:** " + "; ".join(f"{b['brand']} ({b['listings']} лотів, {b['share_pct']}%) {b['new_median_eur_gb'] or '—'}|{b['used_median_eur_gb'] or '—'}" for b in rr))
A("\nВисновки по брендах: роздрібні «геймерські» кіти (G.Skill, Kingston Fury) на ~25–35% дорожчі за ГБ, ніж OEM (Samsung, SK Hynix, Micron) і бюджетні (Crucial, Patriot);")
A("для вживаного різниця менша (11–16 €/ГБ для DDR5). Записи HP/Dell/Lenovo з аномальними цінами — це, ймовірно, робочі станції/спец-модулі, не еталон.\n")

A("## 5. Вплив швидкості на ціну (нове, медіана)\n")
A("DDR5 UDIMM 32 ГБ кіт: 4800 → €475; 5600 → €600; 6000 → €645; 6400 → €632; 7200 → €882; 8000 → €1151 (глибина 132 лоти на 6000 — стандарт).")
A("DDR4 UDIMM 16 ГБ кіт: 2400 → €96; 3200 → €145; 3600 → €178. DDR4 SO-DIMM 16 ГБ: швидкість майже не впливає (€110–114).\n")

A("## 6. Швидкість продажів (чесно)\n")
A("- У вибірці дилерських лотів **продажі по поточних цінах повільні**: медіана 0–0,1 шт/тиж на лот у більшості клітинок; сума по вибірці 0–2 шт/тиж для DDR5 і DDR4 UDIMM/SO-DIMM ≥16 ГБ.")
A("- Найшвидше: DDR4 серверні 32 ГБ (1,8 шт/тиж), DDR4 UDIMM 16 ГБ 1× (1,9), DDR3 4 ГБ (3–9, але це €6–10 за штуку).")
A("- Інтерпретація: ціни оголошень високі, покупці вагаються («buyers balking»), реальна ціна продажу може бути нижчою за «швидку». Це головна невизначеність; перевірка — Terapeak.\n")

A("## 7. Міждержавне порівняння (лоти, фізично розташовані в країні, ціна з доставкою до DE, нове)\n")
A("Спершу я помилково порівнював маркетплейси AT/IT/ES/NL із `deliveryCountry:DE`: це той самий спільний каталог (n=60–180, ціни як у DE). Виправлено: беремо `itemLocationCountry`.\n")
A("| Клітинка | DE | IT | ES | NL | FR | PL |")
A("|---|--:|--:|--:|--:|--:|--:|")
de_by = {f"('{r['gen']}', '{r['form']}', {r['total_gb']}, '{r['kit']}')": r["new_fast"] for r in cells}
byc = defaultdict(dict)
for k, v in cross2.items():
    cell, cc = k.rsplit("|", 1)
    byc[cell][cc] = v
for cell, d in byc.items():
    def fmt(cc):
        x = d.get(cc)
        return f"{x['fast']:.0f} (n={x['n']})" if x and x["fast"] else "—"
    if not any(d.get(cc, {}).get("fast") for cc in ("IT", "ES", "NL", "FR", "PL")):
        continue
    A(f"| {cell.replace(chr(39), '')} | {de_by.get(cell, '—')} | {fmt('IT')} | {fmt('ES')} | {fmt('NL')} | {fmt('FR')} | {fmt('PL')} |")
A("\nВисновок: **німецький eBay найдешевший**. Лоти з IT ≈ DE (DDR5 SO-DIMM), ES/NL/FR на 35–40% дорожчі, AT/IE — у 2–4 рази дорожчі (переважно перепродавці). Купувати за кордоном сенсу немає.")
A("США/Британія з ПДВ 19%: DDR5 UDIMM 32 ГБ кіт GB €495, US €509 проти DE €406–428; DDR4 32 ГБ кіт GB €195, US €177 проти DE €175. Теж дорожче.")
A("Побічна ідея (НЕ перевірена): продаж з DE у ES/NL/IT/FR (+35–40% до ціни) через міжнародні оголошення; потрібні переклад, міжнародна пересилка, VAT/OSS. Це ціни оголошень нечисленних продавців.\n")

A("## 8. Максимальна ціна закупівлі (консервативно)\n")
A("Реалізація = 85% швидкої ціни вживаного (або 75% нового, якщо вживаних <5 продавців); комісія eBay 5% (вживане), пересилка €4,19, повернення 3%, ціль ROI 30%.")
A("Купувати вище цієї ціни не варто. Кожну пропозицію з Kleinanzeigen: `python ram_check.py \"<текст оголошення>\" --buy <ціна>`.\n")
SHIP, FEE = 4.19, 0.05
A("| Тип | Реалізація | Макс. закупівля | Продавців н/в |")
A("|---|--:|--:|--:|")
mb = []
for r in cells:
    us, ns = f(r["used_sellers"]) or 0, f(r["new_sellers"]) or 0
    uf, nf = f(r["used_fast"]), f(r["new_fast"])
    if us >= 5 and uf:
        real = 0.85 * uf
    elif ns >= 5 and nf:
        real = 0.75 * nf
    else:
        continue
    be = real - (FEE * real + 0.45 + SHIP + 0.03 * (2 * SHIP + 0.45))
    if be / 1.3 < 25 or "ecc" in r["form"] or r["gen"] == "ddr3":
        continue
    mb.append((be / 1.3, r, real, ns, us))
for m, r, real, ns, us in sorted(mb, key=lambda x: -x[0]):
    if ns < 8 and us < 5:
        continue
    A(f"| {r['gen'].upper()} {r['form']} {r['total_gb']} ГБ {'кіт' if r['kit'] == 'kit' else '1×'} | €{real:.0f} | €{m:.0f} | {int(ns)}/{int(us)} |")
A("\nЗастереження: серверна DDR4 RDIMM в категорії «Server-Speicher» має комісію 14%: максимальна закупівля нижча (32 ГБ ≈ €56).\n")

A("## 9. МІЙ ВІДБІР\n")
A("### Варто уваги (за пріоритетом)\n")
A("1. **DDR5 UDIMM 32 ГБ (2×16) і 64 ГБ (2×32).** Найглибший DDR5-ринок (56/22 і 37/17 продавців), вживане ≈ ціна нового (€400 vs €406; €676 vs €841), макс. закупівля ≈ €245 і ≈ €416. Ваш приклад (€75) лежить тут.")
A("2. **DDR5 SO-DIMM 16 і 32 ГБ (ноутбуки).** 40/17 і 38/12 продавців, макс. закупівля ≈ €103 і ≈ €186. OEM (Samsung, SK Hynix) ходять по ~€12–15/ГБ і часто трапляються у приватних продавців.")
A("3. **DDR4 UDIMM 32 ГБ кіт** (55/87 продавців): найглибший ринок у всьому дослідженні, вживане €106, макс. закупівля ≈ €62. Менш «дефіцитний», ніж DDR5, зате стабільний.")
A("4. **DDR4 UDIMM 64 ГБ кіт і DDR4 SO-DIMM 32/64 ГБ:** вживане €326 / €144 / €315, макс. закупівля ≈ €199 / €86 / €192.")
A("5. **DDR4 серверні RDIMM 32/64 ГБ:** найкраща швидкість (≈1,8 шт/тиж), вживаний ринок 43–65 продавців. Комісія 14%, потрібна окрема перевірка сумісності покупців.")
A("6. **Слідкувати:** DDR5 UDIMM 16 ГБ та 48 ГБ кіт — вживаного мало (0–4 продавці), але нове дороге.\n")
A("### Не дивитися (немає сенсу)\n")
A("1. **Усе DDR3:** вживане €1,1–3/ГБ, 4–8 ГБ це €6–25; макс. закупівля майже скрізь <€20; постійні витрати (комісія €0,45 + пересилка) з'їдають маржу.")
A("2. **DDR4 4 ГБ і 8 ГБ одиночні; DDR4 16 ГБ будь-який:** реалізація €26–51, макс. закупівля €10–33, швидкість ≈0. Лише «в подарунок» до великої покупки.")
A("3. **ECC-варіанти для ПК/ноутбуків** (UDIMM-ECC, SO-DIMM-ECC): 4–12 продавців, ризик несумісності.")
A("4. **DDR5 серверні RDIMM і DDR3 серверні:** DDR5 RDIMM нове €28–32/ГБ, вживаних 6 лотів, B2B, комісія імовірно 14%; DDR3 серверні майже нічого не варті.")
A("5. **Швидкості 7200–8000+ (ентузіастські):** тонкий ринок, ціни €880–1150 за 32 ГБ, покупців мало.")
A("6. **Лоти, «Auswahl»-варіації, LPDDR/впаяна, дефектні, готові ПК/ноутбуки:** окремі ринки або шум даних.")
A("7. **Лоти «passend für HP/Dell/Lenovo…»:** ціни у 2–4 рази за ГБ вищі за ринок, це не еталон і не варто купувати за цією логікою.")
A("8. **Купівля за кордоном (GB/US/AT/IE/ES/NL/FR):** дорожче за DE після ПДВ, доставки і курсу.\n")

A("## 10. Що не виміряно\n")
A("- Реальні ціни продажу (Terapeak): рекомендую 3 конфігурації — DDR5 32 ГБ кіт, DDR5 SO-DIMM 16 ГБ, DDR4 UDIMM 32 ГБ кіт.")
A("- Пропозиція на Kleinanzeigen: скільки оголошень нижче «максимальної закупівлі» (вручну, 30 хвилин у Suchaufträge).")
A("- Швидкість по клітинках з дуже малим числом дилерських лотів; продаж приватних поштучних лотів повільніший за дилерський.")
A("- Динаміка цін: за прогнозами TrendForce ріст триває, полегшення не раніше середини 2027; запас треба тримати недовго.")
